const byKey = (k: string) => INTENTS.find((i) => i.key === k) ?? null

function detect(text: string): Intent | null {
  if (has(text, 'на дом', 'на дому', 'инсульт', 'лежач', 'не встаёт', 'не встает')) return byKey('home')
  if (has(text, 'гастроэнтеролог', 'печен', 'изжог')) return byKey('gastro')
  if (has(text, 'гастро', 'колоно', 'фгдс', 'эндоскоп', 'желуд', 'кишеч', 'седац', 'наркоз')) return byKey('endo')
  if (has(text, 'ребён', 'ребен', 'сын', 'доч', 'сколиоз', 'осанк', 'дцп', 'плоскостоп', 'сиас')) return byKey('kids')
  if (has(text, 'травм', 'перелом', 'операц', 'кист', 'разработ', 'связк', 'мениск', 'гипс', 'вывих')) return byKey('trauma')
  if (has(text, 'пятк', 'шпор', 'стоп', 'стельк')) return byKey('foot')
  if (has(text, 'колен', 'сустав', 'артроз', 'плеч', 'локот', 'бедр', 'prp', 'плазм', 'магнит')) return byKey('joint')
  if (has(text, 'спин', 'поясниц', 'грыж', 'шея', 'шеи', 'остеохондр', 'позвон', 'протрузи')) return byKey('back')
  if (has(text, 'массаж')) return byKey('massage')
  return null
}

export function nextScriptedReply(s: ConvState): AssistantAction {
  const lastClient = [...s.messages].reverse().find((m) => m.role === 'client')
  const text = (lastClient?.text ?? '').toLowerCase()

  // Жалоба/осложнение/острое состояние → передаём живому специалисту
  if (has(text, 'жалоб', 'осложн', 'температ', 'кровотеч', 'онемел', 'резко хуже', 'не могу встать')) {
    return {
      text: `Спасибо, что написали. Такой случай лучше сразу обсудить со специалистом — я уже передаю его врачу, вам перезвонят в ближайшее время. Если состояние ухудшается — звоните напрямую: ${PHONE}, а при угрозе жизни — 103.`,
      handoff: true,
      leadUpdate: { service: 'Сложный случай', urgency: 'high' },
    }
  }

  const intent = detect(text)
  const isConfirm = CONFIRM.some((c) => text.includes(c))
  const knownService = s.lead.service

  // Подтверждение записи (есть услуга в лиде, брони ещё нет)
  if (isConfirm && knownService && !s.booking) {
    const matched = INTENTS.find((i) => i.service === knownService) ?? byKey('joint')!
    const prep =
      matched.key === 'endo'
        ? ' Пришлю памятку, как подготовиться к обследованию.'
        : ''
    return {
      text:
        matched.key === 'home'
          ? `Отлично, записал выезд: ${matched.slot}. Подскажите, пожалуйста, имя пациента, адрес и номер телефона — специалист позвонит перед выездом.`
          : `Отлично, записал вас! ${matched.doctor}, ${matched.slot}, ${ADDRESS}.${prep} Подскажите, пожалуйста, ваше имя и номер телефона — пришлю подтверждение и напоминание.`,
      booking: { service: matched.service, doctor: matched.doctor, datetime: matched.slot },
    }
  }

  // Новый интент → консультируем + квалифицируем + предлагаем слот
  if (intent) {
    return {
      text: `${intent.reply}\n\nМогу записать вас: ${intent.doctor}, ближайшее окно — ${intent.slot}. Удобно?`,
      leadUpdate: { service: intent.service, urgency: intent.urgency },
    }
  }

  // Имя/телефон в ответ
  if (/\+?\d[\d\s\-()]{6,}/.test(text)) {
    return {
      text:
        'Спасибо! Записал ваши контакты: пришлю подтверждение и напомню за 24, 12, 3 и 1 час до приёма. После визита попрошу оценить приём — нам важен ваш отзыв. Если появятся вопросы — пишите сюда в любое время 😊',
      leadUpdate: { qualified: true },
    }
  }

  // Базовый ответ
  return {
    text:
      'Здравствуйте! Я администратор центра «Орто-Рекавери». Расскажите, что беспокоит — спина, суставы, восстановление после травмы, ребёнок или обследование ЖКТ, — подскажу цену и запишу к нужному специалисту.',
  }
}
